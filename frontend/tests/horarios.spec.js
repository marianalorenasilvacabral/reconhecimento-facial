import { test, expect } from './camera.fixture.js'

test('entrada, saída, duração e consulta exigem login do administrador', async ({ page, request }) => {
  test.setTimeout(60000)
  const api = 'http://127.0.0.1:18000'
  const form = new FormData()
  for (const [chave, valor] of Object.entries({ nome: 'Pessoa Horarios', data_nascimento: '2008-03-15', cpf: '11144477735', consentimento: 'true' })) form.append(chave, valor)
  const foto = Buffer.concat([Buffer.from([255, 216, 255, 224]), Buffer.from('PESSOA=2 foto-teste')])
  for (let i = 0; i < 5; i++) form.append('fotos', new Blob([foto], { type: 'image/jpeg' }), `foto${i}.jpg`)
  expect((await fetch(`${api}/alunos`, { method: 'POST', body: form })).status).toBe(201)
  expect((await request.get(`${api}/admin/pontos`)).status()).toBe(401)

  await page.goto('/#horarios')
  await expect(page.getByRole('heading', { name: 'Criar administrador' })).toBeVisible()
  await page.getByLabel('Usuário do administrador').fill('admin_teste')
  await page.getByLabel('Senha', { exact: true }).fill('SenhaDoTeste2026!')
  await page.getByLabel('Confirme a senha').fill('SenhaDoTeste2026!')
  await page.getByRole('button', { name: 'Criar administrador', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Entradas e saídas' })).toBeVisible()

  // Usa API e banco reais; apenas o reconhecedor é falso neste servidor de testes.
  await page.route('**/identificacoes', async (route) => {
    const resposta = await request.post(`${api}/identificacoes`, { multipart: { imagem: { name: 'quadro.jpg', mimeType: 'image/jpeg', buffer: foto } } })
    await route.fulfill({ status: resposta.status(), json: await resposta.json() })
  })
  await page.getByRole('link', { name: 'Identificação', exact: true }).click()
  await page.getByRole('button', { name: 'Câmera do computador', exact: true }).click()
  const cartao = page.locator('aside.cartao')
  await expect(cartao).toContainText('Pessoa Horarios')
  await expect(cartao.getByRole('heading', { name: 'Entrada registrada' })).toBeVisible()
  await expect(cartao).toContainText('Horário de chegada')
  await page.waitForTimeout(2200)
  await expect(cartao).not.toContainText('Saída registrada')
  await page.getByRole('button', { name: 'Desligar câmera' }).click()
  await page.waitForTimeout(5500)
  await page.getByRole('button', { name: 'Câmera do computador', exact: true }).click()
  await expect(cartao.getByRole('heading', { name: 'Saída registrada' })).toBeVisible({ timeout: 12000 })
  await expect(cartao).toContainText('Horário de saída')
  await expect(cartao).toContainText('Tempo no local')
  await page.getByRole('button', { name: 'Desligar câmera' }).click()

  await page.getByRole('link', { name: 'Horários', exact: true }).click()
  await page.getByLabel('Nome da pessoa').fill('Pessoa Horarios')
  await page.getByRole('button', { name: 'Filtrar', exact: true }).click()
  const linha = page.getByRole('row').filter({ hasText: 'Pessoa Horarios' })
  await expect(linha).toHaveCount(1)
  await expect(linha).not.toContainText('No local')
  await expect(linha).toContainText('00:00:')
  await page.getByRole('button', { name: 'Sair da administração' }).click()
  await expect(page.getByRole('heading', { name: 'Acesso do administrador' })).toBeVisible()
  expect((await page.request.get(`${api}/admin/pontos`)).status()).toBe(401)
  await page.getByLabel('Usuário do administrador').fill('admin_teste')
  await page.getByLabel('Senha', { exact: true }).fill('senha_incorreta')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Usuário ou senha incorretos')
  await page.getByLabel('Senha', { exact: true }).fill('SenhaDoTeste2026!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Entradas e saídas' })).toBeVisible()
})

test('exclusão permite cancelar, exige login e mantém cadastro se o servidor falhar', async ({ page, request }) => {
  const api = 'http://127.0.0.1:18000'
  const credenciais = { usuario: 'admin_teste', senha: 'SenhaDoTeste2026!' }
  const estado = await (await request.get(`${api}/admin/estado`)).json()
  if (!estado.configurado) expect((await request.post(`${api}/admin/configurar`, { data: credenciais })).status()).toBe(201)
  const form = new FormData()
  for (const [chave, valor] of Object.entries({ nome: 'Pessoa Exclusao Navegador', data_nascimento: '2008-03-15', cpf: '39053344705', consentimento: 'true' })) form.append(chave, valor)
  const foto = Buffer.concat([Buffer.from([255, 216, 255, 224]), Buffer.from('PESSOA=3 exclusao-teste')])
  for (let i = 0; i < 5; i++) form.append('fotos', new Blob([foto], { type: 'image/jpeg' }), `foto${i}.jpg`)
  const cadastro = await fetch(`${api}/alunos`, { method: 'POST', body: form })
  expect(cadastro.status).toBe(201)
  const aluno = await cadastro.json()

  await page.goto('/#consulta')
  const item = page.locator('button.cartao-lista').filter({ hasText: 'Pessoa Exclusao Navegador' })
  await item.click()
  await page.getByRole('button', { name: 'Excluir cadastro', exact: true }).click()
  const dialogo = page.getByRole('dialog', { name: 'Excluir cadastro de Pessoa Exclusao Navegador?' })
  await expect(dialogo).toContainText('histórico de entrada e saída')
  await dialogo.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(dialogo).not.toBeVisible()
  expect((await request.get(`${api}/alunos/${aluno.id}`)).status()).toBe(200)

  await page.getByRole('button', { name: 'Excluir cadastro', exact: true }).click()
  await dialogo.getByLabel('Usuário do administrador').fill(credenciais.usuario)
  await dialogo.getByLabel('Senha do administrador').fill('senha_incorreta')
  await dialogo.getByRole('button', { name: 'Entrar e excluir cadastro', exact: true }).click()
  await expect(dialogo.getByRole('alert')).toContainText('Usuário ou senha incorretos')
  expect((await request.get(`${api}/alunos/${aluno.id}`)).status()).toBe(200)

  let falhar = true
  await page.route(`**/admin/alunos/${aluno.id}`, async (route) => {
    if (falhar) return route.fulfill({ status: 503, json: { detail: 'Falha simulada ao excluir o cadastro.' } })
    await route.continue()
  })
  await dialogo.getByLabel('Senha do administrador').fill(credenciais.senha)
  await dialogo.getByRole('button', { name: 'Entrar e excluir cadastro', exact: true }).click()
  await expect(dialogo.getByRole('alert')).toContainText('Falha simulada')
  await expect(item).toHaveCount(1)
  expect((await request.get(`${api}/alunos/${aluno.id}`)).status()).toBe(200)
  falhar = false
  await dialogo.getByRole('button', { name: 'Excluir definitivamente', exact: true }).click()
  await expect(dialogo).not.toBeVisible()
  await expect(page.getByRole('status')).toContainText('Cadastro de Pessoa Exclusao Navegador excluído com sucesso.')
  await expect(item).toHaveCount(0)
  expect((await request.get(`${api}/alunos/${aluno.id}`)).status()).toBe(404)
  expect((await request.get(`${api}/alunos/${aluno.id}/fotos/1`)).status()).toBe(404)
})
